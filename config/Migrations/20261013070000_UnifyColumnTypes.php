<?php
declare(strict_types=1);

use Cake\Core\Configure;
use Migrations\BaseMigration;

/**
 * One schema, however the database came to be.
 *
 * The databases created years ago and those built from the migrations ended up apart, and each
 * was mixed in itself: text limited to 255 characters for no reason, times with a time zone and
 * without one side by side, single-precision floats, and defaults frozen at the moment a migration
 * ran, and numbers handed out by a sequence where the newer ones use an identity column. This
 * brings any of them to the same:
 *
 * - text limited to 255 characters loses the limit, as nothing kept there is bounded by it;
 * - every time keeps its time zone. One without it was written by the application as the local
 *   time of the installation, so it is read in `App.defaultTimezone`; the few the database fills
 *   itself were written in UTC, the time zone its sessions run in;
 * - single-precision floats become double precision;
 * - a time default frozen at a moment, or written as `CURRENT_TIMESTAMP`, becomes `now()`;
 * - a number taken from a sequence becomes an identity column, carrying on where the sequence was.
 *
 * Defaults an installation set for itself, such as a country chosen in advance, are left alone.
 * Tables of plugins long gone are dropped. The migration logs are not touched.
 */
class UnifyColumnTypes extends BaseMigration
{
    /**
     * Tables left behind by plugins no longer used, and by a log written under a misspelt name.
     *
     * @var list<string>
     */
    private const LEFTOVER_TABLES = ['queue_failed_jobs', 'cake_queue_phinxlog', 'cake_d_c_u_sers_phinxlog'];

    /**
     * Times the database writes itself rather than the application, so in UTC.
     *
     * @var list<string>
     */
    private const WRITTEN_IN_UTC = ['fulltext_search_customers.modified'];

    /**
     * Up Method.
     *
     * @return void
     */
    public function up(): void
    {
        $zone = (string)Configure::read('App.defaultTimezone', 'UTC');
        if (!in_array($zone, DateTimeZone::listIdentifiers(), true)) {
            throw new RuntimeException(sprintf('App.defaultTimezone "%s" is not a time zone.', $zone));
        }

        foreach (self::LEFTOVER_TABLES as $table) {
            $this->execute('DROP TABLE IF EXISTS ' . $this->name($table));
        }

        foreach ($this->columns("data_type = 'character varying' AND character_maximum_length = 255") as $column) {
            $this->execute(sprintf('ALTER TABLE %s ALTER COLUMN %s TYPE varchar', $column['table'], $column['name']));
        }

        foreach ($this->columns("data_type = 'timestamp without time zone'") as $column) {
            $this->execute(sprintf(
                "ALTER TABLE %s ALTER COLUMN %2\$s TYPE timestamptz USING %2\$s AT TIME ZONE '%3\$s'",
                $column['table'],
                $column['name'],
                in_array($column['raw'], self::WRITTEN_IN_UTC, true) ? 'UTC' : $zone,
            ));
            if (preg_match("/^('\\d{4}-\\d{2}-\\d{2}|CURRENT_TIMESTAMP)/i", $column['default']) === 1) {
                $this->execute(sprintf(
                    'ALTER TABLE %s ALTER COLUMN %s SET DEFAULT now()',
                    $column['table'],
                    $column['name'],
                ));
            }
        }

        foreach ($this->columns("data_type = 'real'") as $column) {
            $this->execute(sprintf(
                'ALTER TABLE %s ALTER COLUMN %s TYPE double precision',
                $column['table'],
                $column['name'],
            ));
        }

        foreach ($this->columns("column_default LIKE 'nextval(%'") as $column) {
            if (preg_match("/^nextval\\('([^']+)'::regclass\\)$/", $column['default'], $match) !== 1) {
                continue;
            }
            $sequence = $match[1];
            // never a number handed out before, nor one of a record still there
            $row = $this->fetchRow(sprintf(
                'SELECT GREATEST(CASE WHEN is_called THEN last_value + 1 ELSE last_value END, '
                . '(SELECT COALESCE(MAX(%s), 0) + 1 FROM %s)) AS next FROM %s',
                $column['name'],
                $column['table'],
                $sequence,
            ));
            $next = is_array($row) ? (int)$row['next'] : 1;
            $this->execute(sprintf('ALTER TABLE %s ALTER COLUMN %s DROP DEFAULT', $column['table'], $column['name']));
            $this->execute(sprintf('DROP SEQUENCE %s', $sequence));
            $this->execute(sprintf(
                'ALTER TABLE %s ALTER COLUMN %s ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME %s START WITH %d)',
                $column['table'],
                $column['name'],
                $sequence,
                $next,
            ));
        }

        // the only flag that migrations created as required and old databases did not
        if ($this->hasTable('service_types')) {
            $this->execute(
                'UPDATE service_types SET installation_address_required = false '
                . 'WHERE installation_address_required IS NULL',
            );
            $this->execute(
                'ALTER TABLE service_types ALTER COLUMN installation_address_required SET DEFAULT false, '
                . 'ALTER COLUMN installation_address_required SET NOT NULL',
            );
        }
    }

    /**
     * Down Method.
     *
     * @return void
     */
    public function down(): void
    {
        // the old types were a mistake to go back to, not a state worth restoring
    }

    /**
     * Columns of the application's tables matching a condition, quoted for SQL.
     *
     * @param string $condition A condition on `information_schema.columns`.
     * @return list<array{table: string, name: string, raw: string, default: string}>
     */
    private function columns(string $condition): array
    {
        $rows = $this->fetchAll(
            "SELECT c.table_name, c.column_name, COALESCE(c.column_default, '') AS column_default
            FROM information_schema.columns c
            JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
            WHERE c.table_schema = current_schema()
                AND t.table_type = 'BASE TABLE'
                AND t.table_name NOT LIKE '%phinxlog'
                AND t.table_name <> 'cake_migrations'
                AND " . $condition . '
            ORDER BY c.table_name, c.column_name',
        );

        return array_values(array_map(fn(array $row): array => [
            'table' => $this->name((string)$row['table_name']),
            'name' => $this->name((string)$row['column_name']),
            'raw' => $row['table_name'] . '.' . $row['column_name'],
            'default' => (string)$row['column_default'],
        ], $rows));
    }

    /**
     * A name quoted as an identifier.
     *
     * @param string $name The name.
     * @return string
     */
    private function name(string $name): string
    {
        return '"' . str_replace('"', '""', $name) . '"';
    }
}
